private void setEditMode(boolean b) {
    txtName.setEditable(b);
    txtPrice.setEditable(b);
    txtDescription.setEditable(b);
    btnSave.setEnabled(b);
    btnUpdate.setEnabled(!b);
}

private void populateFeatures() {
    DefaultTableModel model = (DefaultTableModel) tblFeatures.getModel();
    model.setRowCount(0);
    for (Feature f : product.getFeatures()) {
        Object[] row = new Object[2];
        row[0] = f.getName();
        row[1] = f.getValue();
        model.addRow(row);
    }
}

