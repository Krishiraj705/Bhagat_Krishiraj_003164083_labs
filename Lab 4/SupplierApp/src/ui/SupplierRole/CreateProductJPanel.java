    private void btnCreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateActionPerformed
       String name = txtName.getText().trim();
String priceText = txtPrice.getText().trim();
String description = txtDescription.getText().trim();

if (name.isEmpty() || priceText.isEmpty() || description.isEmpty()) {
    JOptionPane.showMessageDialog(this, "All fields are mandatory");
    return;
}

double price;
try {
    price = Double.parseDouble(priceText);
} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Price must be a number");
    return;
}

Product p = supplier.getProductCatalog().addProduct();
p.setName(name);
p.setPrice(price);
p.setDescription(description);

JOptionPane.showMessageDialog(this, "Product created! Product ID is " + p.getId());
txtName.setText("");
txtPrice.setText("");
txtDescription.setText("");
    }//GEN-LAST:event_btnCreateActionPerformed

    private void btnBackActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBackActionPerformed
       userProcessContainer.remove(this);
Component[] components = userProcessContainer.getComponents();
Component last = components[components.length - 1];
if (last instanceof ManageProductCatalogJPanel) {
    ((ManageProductCatalogJPanel) last).populateTable();
}
CardLayout layout = (CardLayout) userProcessContainer.getLayout();
layout.previous(userProcessContainer);
    }//GEN-LAST:event_btnBackActionPerformed


