    private void btnViewProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewProductActionPerformed
        int row = tblProducts.getSelectedRow();
if (row < 0) {
    JOptionPane.showMessageDialog(this, "Please select a product");
    return;
}
Product p = (Product) tblProducts.getValueAt(row, 1);
openProduct(p);
    }//GEN-LAST:event_btnViewProductActionPerformed

    private void btnDeleteProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteProductActionPerformed
        int row = tblProducts.getSelectedRow();
if (row < 0) {
    JOptionPane.showMessageDialog(this, "Please select a product");
    return;
}
int choice = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this product?", "Warning", JOptionPane.YES_NO_OPTION);
if (choice == JOptionPane.YES_OPTION) {
    Product p = (Product) tblProducts.getValueAt(row, 1);
    supplier.getProductCatalog().removeProduct(p);
    populateTable();
}
    }//GEN-LAST:event_btnDeleteProductActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
      int id;
try {
    id = Integer.parseInt(txtSearchId.getText().trim());
} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Please enter a valid number for Product ID");
    return;
}
Product p = supplier.getProductCatalog().searchProduct(id);
if (p != null) {
    openProduct(p);
} else {
    JOptionPane.showMessageDialog(this, "Product not found");
}
    }//GEN-LAST:event_btnSearchActionPerformed


