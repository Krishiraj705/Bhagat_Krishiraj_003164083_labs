public void populateTable() {
    DefaultTableModel model = (DefaultTableModel) tblProducts.getModel();
    model.setRowCount(0);
    for (Product p : supplier.getProductCatalog().getProducts()) {
        Object[] row = new Object[3];
        row[0] = p.getId();
        row[1] = p;
        row[2] = p.getPrice();
        model.addRow(row);
    }
}

private void openProduct(Product p) {
    ViewProductJPanel panel = new ViewProductJPanel(userProcessContainer, p);
    userProcessContainer.add("ViewProductJPanel", panel);
    CardLayout layout = (CardLayout) userProcessContainer.getLayout();
    layout.next(userProcessContainer);
}

