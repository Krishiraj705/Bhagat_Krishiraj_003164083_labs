    private void btnAddSupplierActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddSupplierActionPerformed
      String name = txtSupplierName.getText().trim();
if (name.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please enter a supplier name");
    return;
}
for (Supplier s : supplierDirectory.getSuppliers()) {
    if (s.getSupplierName().equalsIgnoreCase(name)) {
        JOptionPane.showMessageDialog(this, "This supplier already exists");
        return;
    }
}
Supplier s = supplierDirectory.addSupplier();
s.setSupplierName(name);
txtSupplierName.setText("");
populateTable();
JOptionPane.showMessageDialog(this, "Supplier added successfully!");
    }//GEN-LAST:event_btnAddSupplierActionPerformed

    private void btnViewProductsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewProductsActionPerformed
       int row = tblSuppliers.getSelectedRow();
if (row < 0) {
    JOptionPane.showMessageDialog(this, "Please select a supplier");
    return;
}
Supplier s = (Supplier) tblSuppliers.getValueAt(row, 0);
ViewSupplierProductsJPanel panel = new ViewSupplierProductsJPanel(userProcessContainer, s);
userProcessContainer.add("ViewSupplierProductsJPanel", panel);
CardLayout layout = (CardLayout) userProcessContainer.getLayout();
layout.next(userProcessContainer);
    }//GEN-LAST:event_btnViewProductsActionPerformed

    private void btnRemoveSupplierActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveSupplierActionPerformed
     int row = tblSuppliers.getSelectedRow();
if (row < 0) {
    JOptionPane.showMessageDialog(this, "Please select a supplier");
    return;
}
int choice = JOptionPane.showConfirmDialog(this, "Are you sure you want to remove this supplier?", "Warning", JOptionPane.YES_NO_OPTION);
if (choice == JOptionPane.YES_OPTION) {
    Supplier s = (Supplier) tblSuppliers.getValueAt(row, 0);
    supplierDirectory.removeSupplier(s);
    populateTable();
}
    }//GEN-LAST:event_btnRemoveSupplierActionPerformed


