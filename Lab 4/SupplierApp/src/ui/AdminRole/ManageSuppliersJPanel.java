public void populateTable() {
    DefaultTableModel model = (DefaultTableModel) tblSuppliers.getModel();
    model.setRowCount(0);
    for (Supplier s : supplierDirectory.getSuppliers()) {
        Object[] row = new Object[2];
        row[0] = s;
        row[1] = s.getProductCatalog().getProducts().size();
        model.addRow(row);
    }
}

