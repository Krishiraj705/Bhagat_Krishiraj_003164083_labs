    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
    String role = (String) cmbRole.getSelectedItem();
if ("Administrator".equals(role)) {
    ManageSuppliersJPanel panel = new ManageSuppliersJPanel(userProcessContainer, supplierDirectory);
    showPanel("ManageSuppliersJPanel", panel);
} else {
    int index = cmbSupplier.getSelectedIndex();
    if (index < 0) {
        JOptionPane.showMessageDialog(this, "No supplier found. Please login as Administrator and add a supplier first.");
        return;
    }
    Supplier supplier = supplierDirectory.getSuppliers().get(index);
    ManageProductCatalogJPanel panel = new ManageProductCatalogJPanel(userProcessContainer, supplier);
    showPanel("ManageProductCatalogJPanel", panel);
}
cmbRole.setEnabled(false);
cmbSupplier.setEnabled(false);
btnLogin.setEnabled(false);
btnLogout.setEnabled(true);
    }//GEN-LAST:event_btnLoginActionPerformed

    private void btnLogoutActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLogoutActionPerformed
      userProcessContainer.removeAll();
userProcessContainer.revalidate();
userProcessContainer.repaint();
cmbRole.setEnabled(true);
cmbRole.setSelectedIndex(0);
btnLogin.setEnabled(true);
btnLogout.setEnabled(false);
    }//GEN-LAST:event_btnLogoutActionPerformed

    private void cmbRoleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbRoleActionPerformed
     if ("Supplier".equals(cmbRole.getSelectedItem())) {
    populateSupplierCombo();
    cmbSupplier.setEnabled(true);
} else {
    cmbSupplier.removeAllItems();
    cmbSupplier.setEnabled(false);
}
    }//GEN-LAST:event_cmbRoleActionPerformed

