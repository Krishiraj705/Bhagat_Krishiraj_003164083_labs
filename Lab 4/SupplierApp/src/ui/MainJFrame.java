private void populateSupplierCombo() {
    cmbSupplier.removeAllItems();
    for (Supplier s : supplierDirectory.getSuppliers()) {
        cmbSupplier.addItem(s.getSupplierName());
    }
}

private void showPanel(String name, JPanel panel) {
    userProcessContainer.removeAll();
    userProcessContainer.add(name, panel);
    CardLayout layout = (CardLayout) userProcessContainer.getLayout();
    layout.next(userProcessContainer);
    userProcessContainer.revalidate();
    userProcessContainer.repaint();
}

