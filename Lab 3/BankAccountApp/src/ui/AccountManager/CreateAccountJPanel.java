    private void btnCreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateActionPerformed
       String accNo = txtAccountNumber.getText().trim();
String bank = txtBankName.getText().trim();
String bal = txtBalance.getText().trim();

if (accNo.isEmpty() || bank.isEmpty() || bal.isEmpty()) {
    JOptionPane.showMessageDialog(this, "All fields are mandatory", "Error", JOptionPane.ERROR_MESSAGE);
    return;
}

double balance;
try {
    balance = Double.parseDouble(bal);
} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Balance must be a number", "Error", JOptionPane.ERROR_MESSAGE);
    return;
}

Account a = accountDirectory.addAccount();
a.setAccountNumber(accNo);
a.setBankName(bank);
a.setBalance(balance);

JOptionPane.showMessageDialog(this, "Account created successfully!");
txtAccountNumber.setText("");
txtBankName.setText("");
txtBalance.setText("");
    }//GEN-LAST:event_btnCreateActionPerformed


