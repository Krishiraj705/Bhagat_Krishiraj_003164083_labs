    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
       int row = tblAccounts.getSelectedRow();
if (row < 0) {
    JOptionPane.showMessageDialog(this, "Please select a row");
    return;
}
int choice = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete?", "Warning", JOptionPane.YES_NO_OPTION);
if (choice == JOptionPane.YES_OPTION) {
    Account a = (Account) tblAccounts.getValueAt(row, 0);
    accountDirectory.deleteAccount(a);
    populateTable();
}
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnViewDetailsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewDetailsActionPerformed
      int row = tblAccounts.getSelectedRow();
if (row < 0) {
    JOptionPane.showMessageDialog(this, "Please select a row");
    return;
}
Account a = (Account) tblAccounts.getValueAt(row, 0);
ViewAccountJPanel panel = new ViewAccountJPanel(userProcessContainer, a);
userProcessContainer.add("ViewAccountJPanel", panel);
CardLayout layout = (CardLayout) userProcessContainer.getLayout();
layout.next(userProcessContainer);
    }//GEN-LAST:event_btnViewDetailsActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
       Account found = accountDirectory.searchAccount(txtSearch.getText().trim());
if (found != null) {
    ViewAccountJPanel panel = new ViewAccountJPanel(userProcessContainer, found);
    userProcessContainer.add("ViewAccountJPanel", panel);
    CardLayout layout = (CardLayout) userProcessContainer.getLayout();
    layout.next(userProcessContainer);
} else {
    JOptionPane.showMessageDialog(this, "Account not found");
}
    }//GEN-LAST:event_btnSearchActionPerformed

