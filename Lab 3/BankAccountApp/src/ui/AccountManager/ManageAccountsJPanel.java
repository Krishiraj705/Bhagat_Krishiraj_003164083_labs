public void populateTable() {
    DefaultTableModel model = (DefaultTableModel) tblAccounts.getModel();
    model.setRowCount(0);
    for (Account a : accountDirectory.getAccounts()) {
        Object[] row = new Object[3];
        row[0] = a;
        row[1] = a.getBankName();
        row[2] = a.getBalance();
        model.addRow(row);
    }
}
