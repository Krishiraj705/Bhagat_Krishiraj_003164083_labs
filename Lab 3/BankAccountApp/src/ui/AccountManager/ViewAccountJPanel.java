    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
       if (txtAccountNumber.getText().trim().isEmpty() || txtBankName.getText().trim().isEmpty()
        || txtBalance.getText().trim().isEmpty()) {
    JOptionPane.showMessageDialog(this, "All fields are mandatory");
    return;
}
try {
    account.setBalance(Double.parseDouble(txtBalance.getText().trim()));
} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Balance must be a number");
    return;
}
account.setAccountNumber(txtAccountNumber.getText().trim());
account.setBankName(txtBankName.getText().trim());
JOptionPane.showMessageDialog(this, "Account updated successfully!");
setEditable(false);
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnBackActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBackActionPerformed
    userProcessContainer.remove(this);
Component[] components = userProcessContainer.getComponents();
Component last = components[components.length - 1];
if (last instanceof ManageAccountsJPanel) {
    ManageAccountsJPanel manage = (ManageAccountsJPanel) last;
    manage.populateTable();
}
CardLayout layout = (CardLayout) userProcessContainer.getLayout();
layout.previous(userProcessContainer);
    }//GEN-LAST:event_btnBackActionPerformed


